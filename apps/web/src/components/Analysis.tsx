import { AlertCircle, CheckCircle2, HelpCircle } from "lucide-react";
import type { Argument, Evaluation } from "../types";
import { Badge } from "./ui";
import type { Tone } from "./ui";

function ArgCard({ a, num, onCite }: { a: Argument; num: (id: string) => number; onCite: (id: string) => void }) {
  return (
    <div className="rounded-xl border border-line bg-panel p-3 text-sm">
      <p className="font-medium">{a.claim}</p>
      <p className="mt-1 text-muted">{a.basis}</p>
      <div className="mt-2 flex flex-wrap gap-1">
        {a.evidenceIds.map((id) => (
          <button key={id} onClick={() => onCite(id)} className="rounded-full border border-line bg-sunk px-2 text-xs hover:border-accent">Source {num(id) || "?"}</button>
        ))}
      </div>
      {a.vulnerabilities && a.vulnerabilities.length > 0 && (
        <ul className="mt-2 list-disc space-y-0.5 pl-4 text-xs text-warn">
          {a.vulnerabilities.map((v) => <li key={v}>{v}</li>)}
        </ul>
      )}
    </div>
  );
}

export function ArgumentsPanel({ pro, con, num, onCite }: { pro: Argument[]; con: Argument[]; num: (id: string) => number; onCite: (id: string) => void }) {
  return (
    <section aria-label="Arguments" className="mt-4">
      <div className="grid gap-3 md:grid-cols-2">
        <div className="space-y-2">
          <h3 className="font-serif text-base font-semibold">Supporting your position</h3>
          {pro.map((a) => <ArgCard key={a.id} a={a} num={num} onCite={onCite} />)}
        </div>
        <div className="space-y-2">
          <h3 className="font-serif text-base font-semibold">What opposing counsel may argue</h3>
          {con.map((a) => <ArgCard key={a.id} a={a} num={num} onCite={onCite} />)}
        </div>
      </div>
      <p className="mt-2 text-xs text-muted">The two sides are generated by different model families to reduce shared blind spots.</p>
    </section>
  );
}

const basisTone: Record<Evaluation["legalBasis"], [string, Tone]> = { supported: ["Supported", "ok"], unsupported: ["Unsupported", "bad"], uncertain: ["Uncertain", "warn"] };

export function EvaluationPanel({ ev }: { ev: Evaluation }) {
  const [bl, bt] = basisTone[ev.legalBasis];
  const row = (label: string, items: string[], icon: "alert" | "help") => (
    <div className="flex gap-2 py-1.5">
      {icon === "alert" ? <AlertCircle size={15} className="mt-0.5 shrink-0 text-warn" /> : <HelpCircle size={15} className="mt-0.5 shrink-0 text-muted" />}
      <div>
        <p className="text-muted">{label}</p>
        {items.length ? <ul className="list-disc pl-4">{items.map((i) => <li key={i}>{i}</li>)}</ul> : <p>None identified</p>}
      </div>
    </div>
  );
  return (
    <section aria-label="Evaluation" className="mt-4 rounded-xl border border-line bg-sunk/50 p-4 text-sm">
      <h3 className="mb-2 flex items-center gap-2 font-serif text-base font-semibold"><CheckCircle2 size={16} className="text-accent" /> Evaluator's assessment</h3>
      <div className="mb-2 flex flex-wrap gap-2">
        <span className="flex items-center gap-1.5">Legal basis <Badge tone={bt}>{bl}</Badge></span>
        <span className="flex items-center gap-1.5">Evidence <Badge tone={ev.evidenceSufficiency === "sufficient" ? "ok" : "warn"}>{ev.evidenceSufficiency}</Badge></span>
      </div>
      <div className="divide-y divide-line">
        {row("Conflicting authorities", ev.conflictingAuthorities, "alert")}
        {row("Missing information", ev.missingInformation, "alert")}
        {row("Unresolved questions", ev.unresolvedQuestions, "help")}
      </div>
      <p className="mt-2 text-xs text-muted">This rates the quality of reasoning and evidence. It does not predict how a court will decide.</p>
    </section>
  );
}
