logger = logging.getLogger("cicero.api.documents")

router = APIRouter(prefix="/api/cases/{case_id}/documents", tags=["documents"])
MAX_FILENAME_LENGTH = 255
PDF_MIME_TYPE = "application/pdf"
DOCX_MIME_TYPE = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
SUPPORTED_UPLOADS = {PDF_MIME_TYPE: ".pdf", DOCX_MIME_TYPE: ".docx"}


class UploadUrlRequest(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)
    filename: str = Field(min_length=1, max_length=MAX_FILENAME_LENGTH)
    content_type: str = Field(min_length=1, max_length=100)
    file_size: int = Field(gt=0)


class UploadUrlResponse(BaseModel):
    document_id: UUID
    version_id: UUID
    upload_url: str
    method: str
    required_headers: dict[str, str]
    expires_in_seconds: int
    max_file_size_bytes: int


class UploadCompleteRequest(BaseModel):
    document_id: UUID
    version_id: UUID
    filename: str = Field(min_length=1, max_length=MAX_FILENAME_LENGTH)
    content_type: str = Field(min_length=1, max_length=100)


class DocumentRead(BaseModel):
    document_id: UUID
    case_id: UUID
    title: str
    document_type: str | None
    status: str
    version_id: UUID
    version_number: int
    original_filename: str
    mime_type: str
    file_size: int
    processing_run_id: UUID
    processing_status: str
    processing_stage: str | None = None


def _safe_filename(filename: str) -> str:
    # Keep only a basename and a conservative character set. The actual GCS
    # object name is generated by the server and never trusts a client path.
    basename = filename.replace("\\\\", "/").split("/")[-1].strip()
    safe = re.sub(r"[^A-Za-z0-9._-]", "_", basename)
    safe = safe[:MAX_FILENAME_LENGTH].strip("._")
    if not safe or safe in {".", ".."}:
        raise HTTPException(status_code=422, detail="Invalid filename.")
    return safe


async def _authorize_case(
    session: AsyncSession, identity: DemoIdentity, case_id: UUID
) -> None:
    membership = await CaseRepository(session).get_member(
        case_id, identity.organization_id, identity.user_id
    )
    case = await CaseRepository(session).get_by_id(
        case_id, organization_id=identity.organization_id
    )
    if case is None or membership is None:
        raise HTTPException(status_code=404, detail="Case not found.")


def _storage(request: Request) -> StorageManager:
    return request.app.state.storage_manager


async def _mark_dispatch_failed(
    settings: Any, payload: dict[str, str], error: Exception
) -> None:
    """Record a failed Pub/Sub dispatch so the run never sits silently pending."""
    manager = DatabaseManager(settings)
    await manager.start()
    try:
        factory = manager.session_factory
        if factory is None:
            return
        async with factory() as session:
            async with session.begin():
                run = await ProcessingRepository(session).set_status(
                    UUID(payload["processing_run_id"]),
                    UUID(payload["organization_id"]),
                    "failed",
                    error_message=f"Processing dispatch failed: {error}"[:2000],
                )
                if run is not None:
                    run.processing_metadata = {
                        **(run.processing_metadata or {}),
                        "state": "dispatch_failed",
                    }
    finally:
        await manager.close()


async def _dispatch_document_job(settings: Any, payload: dict[str, str]) -> None:
    """Attempt immediate direct dispatch to RAG worker /ingest endpoint."""
    worker_url = getattr(settings, "rag_worker_url", None)
    service_token = getattr(settings, "rag_service_token", None)
    if not worker_url:
        return
    try:
        import httpx

        headers = {"Authorization": f"Bearer {service_token}"} if service_token else {}
        async with httpx.AsyncClient(timeout=5.0) as client:
            res = await client.post(
                f"{str(worker_url).rstrip('/')}/ingest",
                json=payload,
                headers=headers,
            )
            if res.status_code == 200:
                logger.info(
                    "Direct RAG worker /ingest accepted run %s",
                    payload.get("processing_run_id"),
                )
    except Exception as exc:
        logger.warning(
            "Direct RAG worker /ingest attempt failed (Pub/Sub will deliver): %s",
            exc,
        )


def _publish_document_job(
    topic_path: str, payload: dict[str, str], settings: Any
) -> None:
    """Publish one document processing event; Pub/Sub retries worker failures.

    Runs as a Starlette background task after the 201 response, so a publish
    failure (e.g. missing pubsub.topics.publish) would otherwise be invisible
    and leave the run pending forever: catch it and mark the run failed.
    """
    try:
        credentials = GoogleCredentialsProvider(settings).load()
        publisher = pubsub_v1.PublisherClient(credentials=credentials)
        future = publisher.publish(topic_path, json.dumps(payload).encode("utf-8"))
        future.result(timeout=20)
    except Exception as exc:
        logger.exception("Document processing dispatch failed")
        _mark_dispatch_failed_sync(settings, payload, exc)


def _mark_dispatch_failed_sync(
    settings: Any, payload: dict[str, str], error: Exception
) -> None:
    try:
        asyncio.run(_mark_dispatch_failed(settings, payload, error))
    except Exception:
        logger.exception("Could not mark processing run as dispatch-failed")


def _object_name(
    organization_id: UUID, case_id: UUID, document_id: UUID, version_id: UUID, filename: str
) -> str:
    return (
        f"orgs/{organization_id}/cases/{case_id}/documents/"
        f"{document_id}/versions/{version_id}/{filename}"
    )


@router.post("/upload-url", response_model=UploadUrlResponse)
async def create_upload_url(
    case_id: UUID,
    payload: UploadUrlRequest,
    request: Request,
    identity: Annotated[DemoIdentity, Depends(get_demo_identity)],
    session: Annotated[AsyncSession, Depends(get_transactional_db_session)],
) -> UploadUrlResponse:
    await _authorize_case(session, identity, case_id)
    filename = _safe_filename(payload.filename)
    settings = request.app.state.settings
    expected_ext = SUPPORTED_UPLOADS.get(payload.content_type.lower())
    if expected_ext is None or not filename.lower().endswith(expected_ext):
        raise HTTPException(
            status_code=415, detail="Only PDF and DOCX documents are supported."
        )
    if payload.file_size > settings.gcs_max_file_size_bytes:
        max_mb = settings.gcs_max_file_size_bytes // (1024 * 1024)
        raise HTTPException(
            status_code=413, detail=f"File exceeds the {max_mb} MiB upload limit."
        )

    document_id, version_id = uuid4(), uuid4()
    object_name = _object_name(
        identity.organization_id, case_id, document_id, version_id, filename
    )
    try:
        signed = await run_in_threadpool(
            _storage(request).generate_upload_url,
            object_name,
            content_type=payload.content_type.lower(),
        )
    except StorageConfigurationError as exc:
        raise HTTPException(status_code=503, detail="Document storage is unavailable.") from exc

    return UploadUrlResponse(
        document_id=document_id,
        version_id=version_id,
        upload_url=signed.url,
        method=signed.method,
        required_headers=signed.required_headers,
        expires_in_seconds=signed.expires_in_seconds,
        max_file_size_bytes=signed.max_file_size_bytes,
    )


@router.post("/complete", response_model=DocumentRead, status_code=status.HTTP_201_CREATED)
async def complete_upload(
    case_id: UUID,
    payload: UploadCompleteRequest,
    request: Request,
    background_tasks: BackgroundTasks,
    identity: Annotated[DemoIdentity, Depends(get_demo_identity)],
    session: Annotated[AsyncSession, Depends(get_transactional_db_session)],
) -> DocumentRead:
    await _authorize_case(session, identity, case_id)
    filename = _safe_filename(payload.filename)
    expected_ext = SUPPORTED_UPLOADS.get(payload.content_type.lower())
    if expected_ext is None or not filename.lower().endswith(expected_ext):
        raise HTTPException(
            status_code=415, detail="Only PDF and DOCX documents are supported."
        )

    repository = DocumentRepository(session)
    if await repository.get_by_id(payload.document_id, organization_id=identity.organization_id):
        raise HTTPException(status_code=409, detail="This upload has already been registered.")

    object_name = _object_name(
        identity.organization_id, case_id, payload.document_id, payload.version_id, filename
    )
    try:
        metadata = await run_in_threadpool(
            _storage(request).get_object_metadata, object_name
        )
    except StorageObjectNotFoundError as exc:
        raise HTTPException(
            status_code=409,
            detail="Uploaded object was not found in storage.",
        ) from exc
    except StorageConfigurationError as exc:
        raise HTTPException(status_code=503, detail="Document storage is unavailable.") from exc

    if metadata.content_type not in SUPPORTED_UPLOADS:
        raise HTTPException(
            status_code=415, detail="Stored object is not marked as a PDF or DOCX."
        )
    max_file_size = request.app.state.settings.gcs_max_file_size_bytes
    if metadata.size_bytes < 1 or metadata.size_bytes > max_file_size:
        raise HTTPException(status_code=413, detail="Stored object has an invalid file size.")

    document = repository.create_document(
        case_id=case_id,
        organization_id=identity.organization_id,
        uploaded_by=identity.user_id,
        title=filename,
        document_type=SUPPORTED_UPLOADS[metadata.content_type],
    )
    # Use the ID generated by the database for the document record. The signed
    # object path is tied to the caller-provided upload ID, so preserve that ID.
    document.document_id = payload.document_id
    await session.flush()
    version = repository.add_version(
        document_id=document.document_id,
        organization_id=identity.organization_id,
        version_number=1,
        original_filename=filename,
        mime_type=metadata.content_type,
        file_size=metadata.size_bytes,
        gcs_bucket=metadata.bucket_name,
        gcs_object_name=metadata.object_name,
        uploaded_by=identity.user_id,
    )
    version.version_id = payload.version_id
    await session.flush()
    run = ProcessingRepository(session).create_run(
        version_id=version.version_id,
        document_id=document.document_id,
        organization_id=identity.organization_id,
        extraction_method="docling",
        processing_metadata={"source": "browser_signed_upload", "state": "awaiting_ingestion"},
    )
    await session.flush()
    topic_path = request.app.state.settings.pubsub_document_topic
    worker_url = getattr(request.app.state.settings, "rag_worker_url", None)
    if topic_path or worker_url:
        job_payload = {
            "organization_id": str(identity.organization_id),
            "case_id": str(case_id),
            "document_id": str(document.document_id),
            "version_id": str(version.version_id),
            "processing_run_id": str(run.processing_run_id),
        }
        if worker_url:
            try:
                await asyncio.wait_for(
                    _dispatch_document_job(request.app.state.settings, job_payload),
                    timeout=3.0,
                )
            except Exception as exc:
                logger.debug("Immediate worker dispatch bypassed: %s", exc)
        if topic_path:
            background_tasks.add_task(
                _publish_document_job,
                topic_path,
                job_payload,
                request.app.state.settings,
            )
    else:
        # No topic or worker configured means nothing will ever pick this run up; fail
        # visibly instead of leaving it pending forever.
        run.processing_status = "failed"
        run.completed_at = datetime.now(UTC).replace(tzinfo=None)
        run.error_message = (
            "Document processing dispatch is not configured "
            "(neither CICERO_PUBSUB_DOCUMENT_TOPIC nor CICERO_RAG_WORKER_URL is available)."
        )
        run.processing_metadata = {
            **(run.processing_metadata or {}),
            "state": "dispatch_not_configured",
        }
    await session.refresh(document)
    await session.refresh(version)
    await session.refresh(run)
    init_stage = "Chunking"
    if run.processing_status == "completed":
        init_stage = "Processed"
    elif run.processing_status == "failed":
        init_stage = "Failed"
    return DocumentRead(
        document_id=document.document_id,
        case_id=document.case_id,
        title=document.title,
        document_type=document.document_type,
        status=document.status,
        version_id=version.version_id,
        version_number=version.version_number,
        original_filename=version.original_filename,
        mime_type=version.mime_type,
        file_size=version.file_size,
        processing_run_id=run.processing_run_id,
        processing_status=run.processing_status,
        processing_stage=init_stage,
    )


@router.get("", response_model=list[DocumentRead])
async def list_documents(
    case_id: UUID,
    identity: Annotated[DemoIdentity, Depends(get_demo_identity)],
    session: Annotated[AsyncSession, Depends(get_transactional_db_session)],
) -> list[DocumentRead]:
    await _authorize_case(session, identity, case_id)
    documents = await DocumentRepository(session).list_by_case(
        case_id, identity.organization_id, status="active", limit=200
    )
    result: list[DocumentRead] = []
    document_repository = DocumentRepository(session)
    processing_repository = ProcessingRepository(session)
    for document in documents:
        versions = await document_repository.list_versions(
            document.document_id, identity.organization_id
        )
        if not versions:
            continue
        version = versions[0]
        runs = await processing_repository.list_runs_for_document(
            document.document_id, identity.organization_id, limit=1
        )
        if not runs:
            continue
        run = runs[0]
        stage = "Chunking"
        if run.processing_status == "completed":
            stage = "Processed"
        elif run.processing_status == "failed":
            stage = "Failed"
        elif run.processing_metadata:
            raw_state = str(run.processing_metadata.get("state") or run.processing_metadata.get("stage") or "").lower()
            if "embed" in raw_state:
                stage = "Embedding"
            elif "chunk" in raw_state or "pars" in raw_state:
                stage = "Chunking"
            elif "download" in raw_state or "upload" in raw_state:
                stage = "Uploading"
            elif raw_state:
                stage = raw_state.capitalize()

        result.append(DocumentRead(
            document_id=document.document_id,
            case_id=document.case_id,
            title=document.title,
            document_type=document.document_type,
            status=document.status,
            version_id=version.version_id,
            version_number=version.version_number,
            original_filename=version.original_filename,
            mime_type=version.mime_type,
            file_size=version.file_size,
            processing_run_id=run.processing_run_id,
            processing_status=run.processing_status,
            processing_stage=stage,
        ))
    return result


@router.delete("/{document_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_document(
    case_id: UUID,
    document_id: UUID,
    identity: Annotated[DemoIdentity, Depends(get_demo_identity)],
    session: Annotated[AsyncSession, Depends(get_transactional_db_session)],
) -> None:
    """Permanently delete a document and all associated Postgres rows and pgvector embeddings."""
    await _authorize_case(session, identity, case_id)
    repo = DocumentRepository(session)
    doc = await repo.get_by_id(document_id, organization_id=identity.organization_id)
    if doc is None or doc.case_id != case_id:
        raise HTTPException(status_code=404, detail="Document not found.")

    from sqlalchemy import delete
    try:
        from cicero.persistence.models.documents import (
            Document,
            DocumentChunk,
            DocumentExtraction,
            DocumentProcessingRun,
            DocumentVersion,
        )
    except ImportError:
        from cicero.db.models.documents import (
            Document,
            DocumentChunk,
            DocumentExtraction,
            DocumentProcessingRun,
            DocumentVersion,
        )

    # 1. Delete all chunks and embeddings (pgvector data)
    await session.execute(
        delete(DocumentChunk).where(
            DocumentChunk.document_id == document_id,
            DocumentChunk.organization_id == identity.organization_id,
        )
    )

    # 2. Delete all extractions
    await session.execute(
        delete(DocumentExtraction).where(
            DocumentExtraction.document_id == document_id,
            DocumentExtraction.organization_id == identity.organization_id,
        )
    )

    # 3. Delete all processing runs
    await session.execute(
        delete(DocumentProcessingRun).where(
            DocumentProcessingRun.document_id == document_id,
            DocumentProcessingRun.organization_id == identity.organization_id,
        )
    )

    # 4. Delete all document versions
    await session.execute(
        delete(DocumentVersion).where(
            DocumentVersion.document_id == document_id,
            DocumentVersion.organization_id == identity.organization_id,
        )
    )

    # 5. Delete the document record itself
    await session.execute(
        delete(Document).where(
            Document.document_id == document_id,
            Document.organization_id == identity.organization_id,
        )
    )
    await session.flush()
